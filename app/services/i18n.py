def normalize_language(language: str | None) -> str:
    if language in SUPPORTED_LANGUAGES:
        return language
    return DEFAULT_LANGUAGE


def get_language(request: Request) -> str:
    return normalize_language(request.session.get("portal_language"))


def set_language(request: Request, language: str) -> str:
    normalized = normalize_language(language)
    request.session["portal_language"] = normalized
    return normalized


def translate(key: str, language: str, **kwargs) -> str:
    resolved_language = normalize_language(language)
    value = TRANSLATIONS.get(resolved_language, {}).get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key) or key
    if kwargs:
        return value.format(**kwargs)
    return value


def translator(language: str) -> Callable[[str], str]:
    return lambda key, **kwargs: translate(key, language, **kwargs)
